/**
 * Exports contract ABIs from Foundry artifacts (run `forge build` in contracts/ first) into
 * engine/src/abi/kin.ts and web/lib/abi.ts, typed `as const` for viem.
 *
 *   bun run scripts/export-abis.ts
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";

const root = join(import.meta.dir, "../..");
const names = ["KinHook", "KinRouter", "KinVault", "KinLaunchFactory", "KinToken"];
let out = "// Generated by engine/scripts/export-abis.ts from contracts/out. Do not edit.\n\n";
for (const n of names) {
  const art = JSON.parse(readFileSync(join(root, `contracts/out/${n}.sol/${n}.json`), "utf8"));
  const lower = n[0]!.toLowerCase() + n.slice(1);
  out += `export const ${lower}Abi = ${JSON.stringify(art.abi)} as const;\n\n`;
}
for (const dest of ["engine/src/abi/kin.ts", "web/lib/abi.ts"]) {
  const p = join(root, dest);
  mkdirSync(dirname(p), { recursive: true });
  writeFileSync(p, out);
  console.log(`wrote ${dest}`);
}
